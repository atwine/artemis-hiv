// The website's API types, generated from the backend's own OpenAPI schema so the two can't drift.
//   npm run api:types   rewrite src/lib/api/openapi.json and src/lib/api/schema.d.ts
//   npm run api:check   fail if the committed files no longer match the backend
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const check = process.argv.includes("--check");
const python = process.env.PYTHON || "python";
const outDir = "src/lib/api";
const work = mkdtempSync(join(tmpdir(), "artemis-api-"));

try {
  const schemaPath = join(work, "openapi.json");
  execFileSync(python, ["scripts/export_openapi.py", schemaPath], { stdio: ["ignore", "ignore", "inherit"] });
  const schemaText = readFileSync(schemaPath, "utf8");
  const header = "// Generated by `npm run api:types` from the backend's OpenAPI schema. Do not edit.\n\n";
  const typesText = header + astToString(await openapiTS(JSON.parse(schemaText)));

  const wanted = { "openapi.json": schemaText, "schema.d.ts": typesText };
  if (check) {
    const stale = Object.entries(wanted).filter(([name, text]) => {
      try {
        return readFileSync(join(outDir, name), "utf8") !== text;
      } catch {
        return true;
      }
    });
    if (stale.length) {
      console.error(`API types are out of date (${stale.map(([n]) => n).join(", ")}). Run: npm run api:types`);
      process.exit(1);
    }
    console.log("API types match the backend.");
  } else {
    for (const [name, text] of Object.entries(wanted)) {
      const tmp = join(outDir, `${name}.tmp`);
      writeFileSync(tmp, text);
      renameSync(tmp, join(outDir, name));
    }
    console.log(`Wrote ${outDir}/openapi.json and ${outDir}/schema.d.ts`);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
