def test_listens_on_this_laptop_only(monkeypatch):
    """network role: the backend listens on 127.0.0.1 unless the setting is changed on purpose."""
    from backend.settings import settings_from_env

    monkeypatch.delenv("ARTEMIS_API_HOST", raising=False)
    monkeypatch.delenv("ARTEMIS_API_ORIGINS", raising=False)
    s = settings_from_env()
    assert s.host == "127.0.0.1"
    assert "*" not in s.allowed_origins
    assert set(s.allowed_hosts) == {"localhost", "127.0.0.1"}


def test_run_command_uses_the_setting(monkeypatch):
    """`python -m backend` passes the host setting to uvicorn, never 0.0.0.0 by default."""
    import backend.__main__ as entry

    seen: Dict[str, Any] = {}
    monkeypatch.delenv("ARTEMIS_API_HOST", raising=False)
    monkeypatch.setattr(entry, "load_dotenv", lambda: None)  # this test is about the default
    monkeypatch.setattr(entry.uvicorn, "run", lambda *a, **kw: seen.update(kw))
    entry.main()
    assert seen["host"] == "127.0.0.1"


def test_database_container_is_on_this_laptop_only():
    """network role: every port the compose file publishes is bound to 127.0.0.1, and the
    password is never written in it."""
    import re
    from pathlib import Path

    text = (Path(__file__).resolve().parents[1] / "backend" / "docker-compose.yml").read_text(encoding="utf-8")
    ports = re.findall(r'^\s*-\s*"([^"]+:\d+)"\s*$', text, re.MULTILINE)
    assert ports and all(p.startswith("127.0.0.1:") for p in ports)
    assert re.search(r"POSTGRES_PASSWORD:\s*\$\{ARTEMIS_DB_PASSWORD:\?", text)


def test_the_grid_in_code_matches_access_md():
    """ACCESS.md section 3, the local row, against backend/access.py's GRID."""
    import re
    from pathlib import Path

    from backend.access import GRID

    text = (Path(__file__).resolve().parents[1] / "ACCESS.md").read_text(encoding="utf-8")
    text = text[text.index("## 3. Permission grid"):text.index("## 4. Route map")]
    header = re.search(r"^\| Role \| (.+) \|$", text, re.MULTILINE).group(1).split(" | ")
    local = re.search(r"^\| local \| (.+) \|$", text, re.MULTILINE).group(1).split(" | ")
    from_file = {data: {a.split("(")[0].strip() for a in cell.split(",")} for data, cell in zip(header, local) if cell != "-"}
    assert from_file == {data: set(actions) for data, actions in GRID["local"].items()}
    assert set(GRID) == {"local"}  # every other role gets nothing
